import rateLimit from 'express-rate-limit';

/**
 * Strict rate limiting for authentication endpoints (prevent brute force & credential stuffing).
 * Limit: 15 requests per 15 minutes per IP.
 */
export const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 15,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: 'Too many authentication attempts. Please try again after 15 minutes.',
  },
});

/**
 * Rate limiting for active exam answer buffering and submissions.
 * Limit: 60 requests per minute per IP.
 */
export const examSubmissionLimiter = rateLimit({
  windowMs: 60 * 1000, // 1 minute
  max: 60,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: 'Too many exam requests. Please wait a moment before sending more answers.',
  },
});

/**
 * General rate limiting for public/standard API routes.
 */
export const apiLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 300,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: 'Too many requests. Please slow down.',
  },
});

